    //// The notification and substitution phases of pipelineEmit (getPipelinePhase).

    // PipelinePhase.Notification: onEmitNode is not noEmitNotification and the node asks for a notification.
    private bool WantsNotification(Node node) => handlers?.OnEmitNode is not null && (handlers.IsEmitNotificationEnabled is null || handlers.IsEmitNotificationEnabled(node));

    // PipelinePhase.Substitution: the substitute (with the current parenthesizer rule applied), or none if the node
    // is not substituted.
    private Node Substitute(EmitHint hint, Node node)
    {
        if (handlers?.SubstituteNode is null)
        {
            return Node.None;
        }
        var substitute = handlers.SubstituteNode(hint, node);
        if (substitute.IsNone || substitute == node)
        {
            return Node.None;
        }
        if (!currentParenthesizerRule.IsNone)
        {
            substitute = ApplyParenthesizerRule(currentParenthesizerRule, substitute);
        }
        return substitute;
    }

    // pipelineEmitWithNotification: onEmitNode(hint, node, the next phase), where the next phase
    // (getNextPipelinePhase(PipelinePhase.Notification, ...)) is chosen, and so the node substituted, before the
    // notification handler runs.
    private void PipelineEmitWithNotification(EmitHint hint, Node node)
    {
        var substitute = Substitute(hint, node);
        if (!substitute.IsNone)
        {
            lastSubstitution = substitute;
            handlers!.OnEmitNode!(hint, node, pipelineEmitWithSubstitutionCallback ??= PipelineEmitWithSubstitution);
        }
        else
        {
            handlers!.OnEmitNode!(hint, node, pipelineEmitAfterNotificationCallback ??= PipelineEmitAfterNotification);
        }
    }

    // pipelineEmitWithSubstitution: the phases after substitution with the substitute.
    private void PipelineEmitWithSubstitution(EmitHint hint, Node node)
    {
        Debug.Assert(!lastSubstitution.IsNone);
        node = lastSubstitution;
        lastSubstitution = Node.None;
        PipelineEmitAfterNotification(hint, node);
    }

    // getPipelinePhase(PipelinePhase.Substitution, ...) and the phases after it.
    private void PipelineEmitFromSubstitution(EmitHint hint, Node node)
    {
        var substitute = Substitute(hint, node);
        if (!substitute.IsNone)
        {
            // pipelineEmitWithSubstitution
            node = substitute;
        }
        PipelineEmitAfterNotification(hint, node);
    }

    /// <summary>
    /// emitBinaryExpression's maybeEmitExpression: emits an operand of a binary expression through the pipeline with
    /// the operand's parenthesizer rule, or returns the binary expression to descend into (the operand, or its
    /// substitute, when no notification phase remains).
    /// </summary>
    private Node MaybeEmitBinaryOperand(Node next, Node parent, bool isLeft)
    {
        if (handlers is null)
        {
            // (A printer without print handlers: no notification or substitution phase; the type printer's
            // underlining is PipelineEmit's.)
            if (store.Kind(next) == SyntaxKind.BinaryExpression)
            {
                return next;
            }
            PipelineEmit(EmitHint.Expression, next);
            return Node.None;
        }

        var operatorKind = store.Kind(store.OperatorToken(parent));
        var parenthesizerRule = new ParenthesizerRule(isLeft ? ParenthesizerRuleKind.LeftSideOfBinary : ParenthesizerRuleKind.RightSideOfBinary, operatorKind);

        // getPipelinePhase(PipelinePhase.Notification, EmitHint.Expression, next)
        if (WantsNotification(next))
        {
            currentParenthesizerRule = parenthesizerRule;
            PipelineEmitWithNotification(EmitHint.Expression, next);
            currentParenthesizerRule = default;
            return Node.None;
        }
        if (handlers.SubstituteNode is not null)
        {
            var substitute = handlers.SubstituteNode(EmitHint.Expression, next);
            if (!substitute.IsNone && substitute != next)
            {
                next = ApplyParenthesizerRule(parenthesizerRule, substitute);
            }
        }

        // (the next phase is the comments phase or the emit itself)
        if (store.Kind(next) == SyntaxKind.BinaryExpression)
        {
            return next;
        }

        currentParenthesizerRule = parenthesizerRule;
        PipelineEmitAfterNotification(EmitHint.Expression, next);
        currentParenthesizerRule = default;
        return Node.None;
    }

    //// Emit helpers

    // emitHelpers(node): writes the helpers of the node; whether any was written.
    private bool EmitHelpers(Node node)
    {
        var helpersEmitted = false;
        var sourceFile = store.Kind(node) == SyntaxKind.SourceFile ? node : currentSourceFile;
        var shouldSkip = printerOptions.NoEmitHelpers || (!sourceFile.IsNone && HasRecordedExternalHelpers(sourceFile));
        var helpers = GetSortedEmitHelpers(node);
        if (helpers is not null)
        {
            foreach (var helper in helpers)
            {
                if (!helper.Scoped)
                {
                    // Skip the helper if it can be skipped and the noEmitHelpers compiler
                    // option is set, or if it can be imported and the importHelpers compiler
                    // option is set.
                    if (shouldSkip)
                    {
                        continue;
                    }

                    // (Bundled helpers: no bundles in Track O, isOwnFileEmit is true.)
                }
                if (helper.Text is not null)
                {
                    WriteLines(helper.Text);
                }
                else
                {
                    WriteLines(helper.TextCallback!(MakeFileLevelOptimisticUniqueName));
                }
                helpersEmitted = true;
            }
        }

        return helpersEmitted;
    }

    // factory/utilities.ts hasRecordedExternalHelpers (importHelpers is not an option of Phase 4: never recorded).
    private bool HasRecordedExternalHelpers(Node sourceFile)
    {
        var parseNode = GetOriginalNode(sourceFile);
        var emitNode = store.EmitNode(parseNode) as EmitNode;
        return emitNode is not null && (!emitNode.ExternalHelpersModuleName.IsNone || emitNode.ExternalHelpers == true);
    }

    private List<EmitHelper>? GetSortedEmitHelpers(Node node)
    {
        var helpers = FactoryEmitNode.GetEmitHelpers(store, node);
        if (helpers is null)
        {
            return null;
        }
        // toSorted with compareEmitHelpers: a stable sort.
        var sorted = new List<EmitHelper>(helpers);
        var keyed = new List<(EmitHelper Helper, int Index)>(sorted.Count);
        for (var i = 0; i < sorted.Count; i++)
        {
            keyed.Add((sorted[i], i));
        }
        keyed.Sort((a, b) =>
        {
            var c = EmitHelper.Compare(a.Helper, b.Helper);
            return c != 0 ? c : a.Index.CompareTo(b.Index);
        });
        for (var i = 0; i < keyed.Count; i++)
        {
            sorted[i] = keyed[i].Helper;
        }
        return sorted;
    }

    private void WriteLines(string text)
    {
        var lines = text.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n').Split('\n');
        var indentation = GuessIndentation(lines);
        foreach (var lineText in lines)
        {
            var line = indentation != 0 ? (lineText.Length > indentation ? lineText[indentation..] : "") : lineText;
            if (line.Length != 0)
            {
                WriteLine();
                Write(line);
            }
        }
    }

    // utilities.ts guessIndentation
    private static int GuessIndentation(string[] lines)
    {
        var indentation = int.MaxValue;
        foreach (var line in lines)
        {
            if (line.Length == 0)
            {
                continue;
            }
            var i = 0;
            for (; i < line.Length && i < indentation; i++)
            {
                if (!Scanner.IsWhiteSpaceLike(line[i]))
                {
                    break;
                }
            }
            if (i < indentation)
            {
                indentation = i;
            }
            if (indentation == 0)
            {
                return 0;
            }
        }
        return indentation == int.MaxValue ? 0 : indentation;
    }

    //// Name generation

    /// <summary>Push a new name generation scope.</summary>
    private void PushNameGenerationScope(Node node)
    {
        privateNameTempFlagsStack.Add(privateNameTempFlags);
        privateNameTempFlags = TempFlagsAuto;
        reservedPrivateNamesStack.Add(reservedPrivateNames);

        if (!node.IsNone && (GetEmitFlags(node) & EmitFlags.ReuseTempVariableScope) != 0)
        {
            return;
        }

        tempFlagsStack.Add(tempFlags);
        tempFlags = TempFlagsAuto;
        formattedNameTempFlagsStack.Add(formattedNameTempFlags);
        formattedNameTempFlags = null;
        reservedNamesStack.Add(reservedNames);
    }

    /// <summary>Pop the current name generation scope.</summary>
    private void PopNameGenerationScope(Node node)
    {
        privateNameTempFlags = Pop(privateNameTempFlagsStack);
        reservedPrivateNames = Pop(reservedPrivateNamesStack);

        if (!node.IsNone && (GetEmitFlags(node) & EmitFlags.ReuseTempVariableScope) != 0)
        {
            return;
        }

        tempFlags = Pop(tempFlagsStack);
        formattedNameTempFlags = Pop(formattedNameTempFlagsStack);
        reservedNames = Pop(reservedNamesStack);
    }

    private static T Pop<T>(List<T> stack)
    {
        var value = stack[^1];
        stack.RemoveAt(stack.Count - 1);
        return value;
    }

    private void ReserveNameInNestedScopes(string name)
    {
        if (reservedNames is null || (reservedNamesStack.Count > 0 && ReferenceEquals(reservedNames, reservedNamesStack[^1])))
        {
            reservedNames = new HashSet<string>(StringComparer.Ordinal);
        }
        reservedNames.Add(name);
    }

    private void ReservePrivateNameInNestedScopes(string name)
    {
        if (reservedPrivateNames is null || (reservedPrivateNamesStack.Count > 0 && ReferenceEquals(reservedPrivateNames, reservedPrivateNamesStack[^1])))
        {
            reservedPrivateNames = new HashSet<string>(StringComparer.Ordinal);
        }
        reservedPrivateNames.Add(name);
    }

    private void GenerateNamesOfList(NodeList list)
    {
        foreach (var node in store.Nodes(list))
        {
            GenerateNames(node);
        }
    }

    private void GenerateNames(Node node)
    {
        if (node.IsNone)
        {
            return;
        }
        switch (store.Kind(node))
        {
            case SyntaxKind.Block:
                GenerateNamesOfList(store.Statements(node));
                break;
            case SyntaxKind.LabeledStatement:
            case SyntaxKind.WithStatement:
            case SyntaxKind.DoStatement:
            case SyntaxKind.WhileStatement:
                GenerateNames(store.Statement(node));
                break;
            case SyntaxKind.IfStatement:
                GenerateNames(store.ThenStatement(node));
                GenerateNames(store.ElseStatement(node));
                break;
            case SyntaxKind.ForStatement:
            case SyntaxKind.ForOfStatement:
            case SyntaxKind.ForInStatement:
                GenerateNames(store.Initializer(node));
                GenerateNames(store.Statement(node));
                break;
            case SyntaxKind.SwitchStatement:
                GenerateNames(store.CaseBlock(node));
                break;
            case SyntaxKind.CaseBlock:
                GenerateNamesOfList(store.Clauses(node));
                break;
            case SyntaxKind.CaseClause:
            case SyntaxKind.DefaultClause:
                GenerateNamesOfList(store.Statements(node));
                break;
            case SyntaxKind.TryStatement:
                GenerateNames(store.TryBlock(node));
                GenerateNames(store.CatchClause(node));
                GenerateNames(store.FinallyBlock(node));
                break;
            case SyntaxKind.CatchClause:
                GenerateNames(store.VariableDeclaration(node));
                GenerateNames(store.Block(node));
                break;
            case SyntaxKind.VariableStatement:
                GenerateNames(store.DeclarationList(node));
                break;
            case SyntaxKind.VariableDeclarationList:
                GenerateNamesOfList(store.Declarations(node));
                break;
            case SyntaxKind.VariableDeclaration:
            case SyntaxKind.Parameter:
            case SyntaxKind.BindingElement:
            case SyntaxKind.ClassDeclaration:
                GenerateNameIfNeeded(store.Name(node));
                break;
            case SyntaxKind.FunctionDeclaration:
                GenerateNameIfNeeded(store.Name(node));
                if ((GetEmitFlags(node) & EmitFlags.ReuseTempVariableScope) != 0)
                {
                    GenerateNamesOfList(store.Parameters(node));
                    GenerateNames(store.Body(node));
                }
                break;
            case SyntaxKind.ObjectBindingPattern:
            case SyntaxKind.ArrayBindingPattern:
                GenerateNamesOfList(store.Elements(node));
                break;
            case SyntaxKind.ImportDeclaration:
                GenerateNames(store.ImportClause(node));
                break;
            case SyntaxKind.ImportClause:
                GenerateNameIfNeeded(store.Name(node));
                GenerateNames(store.NamedBindings(node));
                break;
            case SyntaxKind.NamespaceImport:
                GenerateNameIfNeeded(store.Name(node));
                break;
            case SyntaxKind.NamespaceExport:
                GenerateNameIfNeeded(store.Name(node));
                break;
            case SyntaxKind.NamedImports:
                GenerateNamesOfList(store.Elements(node));
                break;
            case SyntaxKind.ImportSpecifier:
                GenerateNameIfNeeded(store.PropertyName(node).IsNone ? store.Name(node) : store.PropertyName(node));
                break;
        }
    }

    private void GenerateMemberNamesOfList(NodeList list)
    {
        foreach (var node in store.Nodes(list))
        {
            GenerateMemberNames(node);
        }
    }

    private void GenerateMemberNames(Node node)
    {
        if (node.IsNone)
        {
            return;
        }
        switch (store.Kind(node))
        {
            case SyntaxKind.PropertyAssignment:
            case SyntaxKind.ShorthandPropertyAssignment:
            case SyntaxKind.PropertyDeclaration:
            case SyntaxKind.PropertySignature:
            case SyntaxKind.MethodDeclaration:
            case SyntaxKind.MethodSignature:
            case SyntaxKind.GetAccessor:
            case SyntaxKind.SetAccessor:
                GenerateNameIfNeeded(store.Name(node));
                break;
        }
    }

    private void GenerateNameIfNeeded(Node name)
    {
        if (!name.IsNone)
        {
            if (IsGeneratedName(name))
            {
                GenerateName(name);
            }
            else if (store.Kind(name) is SyntaxKind.ObjectBindingPattern or SyntaxKind.ArrayBindingPattern)
            {
                GenerateNames(name);
            }
        }
    }

    // isGeneratedIdentifier(name) || isGeneratedPrivateIdentifier(name)
    private bool IsGeneratedName(Node name) =>
        store.Kind(name) is SyntaxKind.Identifier or SyntaxKind.PrivateIdentifier && FactoryEmitNode.GetIdentifierAutoGenerate(store, name) is not null;

    /// <summary>Generate the text for a generated identifier.</summary>
    private string GenerateName(Node name)
    {
        var autoGenerate = FactoryEmitNode.GetIdentifierAutoGenerate(store, name)!;
        if ((autoGenerate.Flags & GeneratedIdentifierFlags.KindMask) == GeneratedIdentifierFlags.Node)
        {
            // Node names generate unique names based on their original node
            // and are cached based on that node's id.
            return GenerateNameCached(GetNodeForGeneratedName(name), store.Kind(name) == SyntaxKind.PrivateIdentifier, autoGenerate.Flags, autoGenerate.Prefix, autoGenerate.Suffix);
        }
        // Auto, Loop, and Unique names are cached based on their unique
        // autoGenerateId.
        var autoGenerateId = autoGenerate.Id;
        if (!autoGeneratedIdToGeneratedName.TryGetValue(autoGenerateId, out var generated))
        {
            generated = MakeName(name);
            autoGeneratedIdToGeneratedName[autoGenerateId] = generated;
        }
        return generated;
    }

    private string GenerateNameCached(Node node, bool privateName, GeneratedIdentifierFlags flags = GeneratedIdentifierFlags.None, string prefix = "", string suffix = "")
    {
        var cache = privateName ? nodeIdToGeneratedPrivateName : nodeIdToGeneratedName;
        if (!cache.TryGetValue(node, out var name))
        {
            name = GenerateNameForNode(node, privateName, flags, NodeFactory.FormatGeneratedNamePart(prefix), NodeFactory.FormatGeneratedNamePart(suffix));
            cache[node] = name;
        }
        return name;
    }

    // factory/utilities.ts getNodeForGeneratedName
    private Node GetNodeForGeneratedName(Node name)
    {
        var autoGenerate = FactoryEmitNode.GetIdentifierAutoGenerate(store, name)!;
        if ((autoGenerate.Flags & GeneratedIdentifierFlags.Node) != 0)
        {
            var autoGenerateId = autoGenerate.Id;
            var node = name;
            var original = store.Original(node);
            while (!original.IsNone)
            {
                node = original;
                var nodeAutoGenerate = FactoryEmitNode.GetIdentifierAutoGenerate(store, node);
                // if "node" is a different generated name (having a different "autoGenerateId"), use it and stop traversing.
                if (store.Kind(node) is SyntaxKind.Identifier or SyntaxKind.PrivateIdentifier &&
                    (nodeAutoGenerate is null || ((nodeAutoGenerate.Flags & GeneratedIdentifierFlags.Node) != 0 && nodeAutoGenerate.Id != autoGenerateId)))
                {
                    break;
                }
                original = store.Original(node);
            }
            // otherwise, return the original node for the source
            return node;
        }
        return name;
    }

    /// <summary>Whether a name is unique globally, within the current file, or within the NameGenerator.</summary>
    private bool IsUniqueName(string name, bool privateName)
    {
        return IsFileLevelUniqueNameInCurrentFile(name, privateName)
            && !IsReservedName(name, privateName)
            && !generatedNames.Contains(name);
    }

    private bool IsReservedName(string name, bool privateName)
    {
        HashSet<string>? set;
        List<HashSet<string>?> stack;
        if (privateName)
        {
            set = reservedPrivateNames;
            stack = reservedPrivateNamesStack;
        }
        else
        {
            set = reservedNames;
            stack = reservedNamesStack;
        }

        if (set is not null && set.Contains(name))
        {
            return true;
        }
        for (var i = stack.Count - 1; i >= 0; i--)
        {
            if (ReferenceEquals(set, stack[i]))
            {
                continue;
            }
            set = stack[i];
            if (set is not null && set.Contains(name))
            {
                return true;
            }
        }
        return false;
    }

    /// <summary>Whether a name is unique globally or within the current file (utilities.ts isFileLevelUniqueName).</summary>
    private bool IsFileLevelUniqueNameInCurrentFile(string name, bool isPrivate)
    {
        if (currentSourceFile.IsNone)
        {
            return true;
        }
        if (handlers?.HasGlobalName is not null && handlers.HasGlobalName(name))
        {
            return false;
        }
        if (currentSourceFileIdentifiers is null || currentSourceFileIdentifiersFile != currentSourceFile)
        {
            // sourceFile.identifiers: the identifiers the parse interned (Track O: the interned texts of the file's store).
            currentSourceFileIdentifiers = new HashSet<string>(store.Texts.ToDictionary().Keys, StringComparer.Ordinal);
            currentSourceFileIdentifiersFile = currentSourceFile;
        }
        return !currentSourceFileIdentifiers.Contains(name);
    }

    private int GetTempFlags(string formattedNameKey)
    {
        switch (formattedNameKey)
        {
            case "":
                return tempFlags;
            case "#":
                return privateNameTempFlags;
            default:
                return formattedNameTempFlags is not null && formattedNameTempFlags.TryGetValue(formattedNameKey, out var flags) ? flags : TempFlagsAuto;
        }
    }

    private void SetTempFlags(string formattedNameKey, int flags)
    {
        switch (formattedNameKey)
        {
            case "":
                tempFlags = flags;
                break;
            case "#":
                privateNameTempFlags = flags;
                break;
            default:
                formattedNameTempFlags ??= new Dictionary<string, int>(StringComparer.Ordinal);
                formattedNameTempFlags[formattedNameKey] = flags;
                break;
        }
    }

    /// <summary>
    /// Return the next available name in the pattern _a ... _z, _0, _1, ...
    /// TempFlags._i may be used to express a preference for that dedicated name.
    /// Note that names generated by makeTempVariableName and makeUniqueName will never conflict.
    /// </summary>
    private string MakeTempVariableName(int flags, bool reservedInNestedScopes, bool privateName, string prefix, string suffix)
    {
        if (prefix.Length > 0 && prefix[0] == '#')
        {
            prefix = prefix[1..];
        }

        // Generate a key to use to acquire a TempFlags counter based on the fixed portions of the generated name.
        var key = NodeFactory.FormatGeneratedName(privateName, prefix, "", suffix);
        var currentFlags = GetTempFlags(key);

        if (flags != 0 && (currentFlags & flags) == 0)
        {
            var name = flags == TempFlags_i ? "_i" : "_n";
            var fullName = NodeFactory.FormatGeneratedName(privateName, prefix, name, suffix);
            if (IsUniqueName(fullName, privateName))
            {
                currentFlags |= flags;
                if (privateName)
                {
                    ReservePrivateNameInNestedScopes(fullName);
                }
                else if (reservedInNestedScopes)
                {
                    ReserveNameInNestedScopes(fullName);
                }
                SetTempFlags(key, currentFlags);
                return fullName;
            }
        }

        while (true)
        {
            var count = currentFlags & TempFlagsCountMask;
            currentFlags++;
            // Skip over 'i' and 'n'
            if (count != 8 && count != 13)
            {
                var name = count < 26
                    ? "_" + (char)('a' + count)
                    : "_" + (count - 26).ToString(System.Globalization.CultureInfo.InvariantCulture);
                var fullName = NodeFactory.FormatGeneratedName(privateName, prefix, name, suffix);
                if (IsUniqueName(fullName, privateName))
                {
                    if (privateName)
                    {
                        ReservePrivateNameInNestedScopes(fullName);
                    }
                    else if (reservedInNestedScopes)
                    {
                        ReserveNameInNestedScopes(fullName);
                    }
                    SetTempFlags(key, currentFlags);
                    return fullName;
                }
            }
        }
    }

    /// <summary>
    /// Generate a name that is unique within the current file and doesn't conflict with any names in global scope: the
    /// base name with an '_n' suffix (n a positive integer). If `optimistic` is set, the first instance uses the base
    /// name verbatim.
    /// </summary>
    private string MakeUniqueName(string baseName, Func<string, bool, bool>? checkFn, bool optimistic, bool scoped, bool privateName, string prefix, string suffix)
    {
        checkFn ??= IsUniqueName;
        if (baseName.Length > 0 && baseName[0] == '#')
        {
            baseName = baseName[1..];
        }
        if (prefix.Length > 0 && prefix[0] == '#')
        {
            prefix = prefix[1..];
        }
        if (optimistic)
        {
            var fullName = NodeFactory.FormatGeneratedName(privateName, prefix, baseName, suffix);
            if (checkFn(fullName, privateName))
            {
                if (privateName)
                {
                    ReservePrivateNameInNestedScopes(fullName);
                }
                else if (scoped)
                {
                    ReserveNameInNestedScopes(fullName);
                }
                else
                {
                    generatedNames.Add(fullName);
                }
                return fullName;
            }
        }
        // Find the first unique 'name_n', where n is a positive number
        if (baseName.Length == 0 || baseName[^1] != '_')
        {
            baseName += "_";
        }
        var i = 1;
        while (true)
        {
            var fullName = NodeFactory.FormatGeneratedName(privateName, prefix, baseName + i.ToString(System.Globalization.CultureInfo.InvariantCulture), suffix);
            if (checkFn(fullName, privateName))
            {
                if (privateName)
                {
                    ReservePrivateNameInNestedScopes(fullName);
                }
                else if (scoped)
                {
                    ReserveNameInNestedScopes(fullName);
                }
                else
                {
                    generatedNames.Add(fullName);
                }
                return fullName;
            }
            i++;
        }
    }

    private string MakeFileLevelOptimisticUniqueName(string name)
    {
        return MakeUniqueName(name, IsFileLevelUniqueNameInCurrentFile, optimistic: true, scoped: false, privateName: false, prefix: "", suffix: "");
    }

    /// <summary>
    /// Track O (module D2): the binder output of the printed file, for isUniqueLocalName (TypeScript reads `node.locals`
    /// and `node.nextContainer` from the nodes). The printed store is the file's emit copy, whose parse tree nodes have
    /// the file's handles; synthesized nodes have none of the binder's fields. Null when the printer prints no file of
    /// a program (the type printer).
    /// </summary>
    internal BinderStore? Binding { get; set; }

    /// <summary>Whether no container from <paramref name="container"/> on declares a local value named <paramref name="nameText"/>.</summary>
    private bool IsUniqueLocalName(TextRef name, Node container)
    {
        if (Binding is null)
        {
            throw new InvalidOperationException("isUniqueLocalName needs the binder output of the printed file.");
        }
        for (var node = container; !node.IsNone && IsNodeDescendantOf(node, container); node = Binding.NextContainerOf(node))
        {
            if (Utilities.CanHaveLocals(store, node))
            {
                var locals = Binding.LocalsOf(node);
                if (!locals.IsNone)
                {
                    var local = Binding.Get(locals, name);
                    // We conservatively include alias symbols to cover cases where they're emitted as locals
                    if (!local.IsNone && (Binding.Flags(local) & (SymbolFlags.Value | SymbolFlags.ExportValue | SymbolFlags.Alias)) != 0)
                    {
                        return false;
                    }
                }
            }
        }
        return true;
    }

    // utilities.ts isNodeDescendantOf
    private bool IsNodeDescendantOf(Node node, Node ancestor)
    {
        while (!node.IsNone)
        {
            if (node == ancestor)
            {
                return true;
            }
            node = store.Parent(node);
        }
        return false;
    }

    private string GenerateNameForModuleOrEnum(Node node)
    {
        var nameNode = store.Name(node);
        var name = GetTextOfNode(nameNode);
        // Use module/enum name itself if it is unique, otherwise make a unique variation
        // (tryCast(node, canHaveLocals): a module declaration; an enum declaration has no locals, so its name is unique.)
        // escapeLeadingUnderscores(name): the name's escaped text (the identifier's own, TypeScript's getTextOfNode
        // of an identifier being its text).
        var isUnique = !Utilities.CanHaveLocals(store, node) || IsUniqueLocalName(store.EscapedText(nameNode), node);
        return isUnique ? name : MakeUniqueName(name, IsUniqueName, optimistic: false, scoped: false, privateName: false, prefix: "", suffix: "");
    }

    /// <summary>Generates a unique name for an ImportDeclaration or ExportDeclaration.</summary>
    private string GenerateNameForImportOrExportDeclaration(Node node)
    {
        var expr = store.ModuleSpecifier(node);
        var baseName = store.Kind(expr) == SyntaxKind.StringLiteral ?
            MakeIdentifierFromModuleName(PrinterUtilities.TextOf(store, expr)) : "module";
        return MakeUniqueName(baseName, IsUniqueName, optimistic: false, scoped: false, privateName: false, prefix: "", suffix: "");
    }

    // utilities.ts makeIdentifierFromModuleName: `getBaseFileName(moduleName).replace(/^(\d)/, "_$1").replace(/\W/g, "_")`
    private static string MakeIdentifierFromModuleName(string moduleName)
    {
        var baseName = TsPath.GetBaseFileName(moduleName);
        var builder = new System.Text.StringBuilder(baseName.Length + 1);
        if (baseName.Length > 0 && baseName[0] is >= '0' and <= '9')
        {
            builder.Append('_');
        }
        foreach (var c in baseName)
        {
            builder.Append(c is (>= 'a' and <= 'z') or (>= 'A' and <= 'Z') or (>= '0' and <= '9') or '_' ? c : '_');
        }
        return builder.ToString();
    }

    /// <summary>Generates a unique name for a default export.</summary>
    private string GenerateNameForExportDefault()
    {
        return MakeUniqueName("default", IsUniqueName, optimistic: false, scoped: false, privateName: false, prefix: "", suffix: "");
    }

    /// <summary>Generates a unique name for a class expression.</summary>
    private string GenerateNameForClassExpression()
    {
        return MakeUniqueName("class", IsUniqueName, optimistic: false, scoped: false, privateName: false, prefix: "", suffix: "");
    }

    private string GenerateNameForMethodOrAccessor(Node node, bool privateName, string prefix, string suffix)
    {
        if (store.Kind(store.Name(node)) == SyntaxKind.Identifier)
        {
            return GenerateNameCached(store.Name(node), privateName);
        }
        return MakeTempVariableName(TempFlagsAuto, reservedInNestedScopes: false, privateName, prefix, suffix);
    }

    /// <summary>Generates a unique name from a node.</summary>
    private string GenerateNameForNode(Node node, bool privateName, GeneratedIdentifierFlags flags, string prefix, string suffix)
    {
        switch (store.Kind(node))
        {
            case SyntaxKind.Identifier:
            case SyntaxKind.PrivateIdentifier:
                return MakeUniqueName(
                    GetTextOfNode(node),
                    IsUniqueName,
                    (flags & GeneratedIdentifierFlags.Optimistic) != 0,
                    (flags & GeneratedIdentifierFlags.ReservedInNestedScopes) != 0,
                    privateName,
                    prefix,
                    suffix);
            case SyntaxKind.ModuleDeclaration:
            case SyntaxKind.EnumDeclaration:
                Debug.Assert(prefix.Length == 0 && suffix.Length == 0 && !privateName);
                return GenerateNameForModuleOrEnum(node);
            case SyntaxKind.ImportDeclaration:
            case SyntaxKind.ExportDeclaration:
                Debug.Assert(prefix.Length == 0 && suffix.Length == 0 && !privateName);
                return GenerateNameForImportOrExportDeclaration(node);
            case SyntaxKind.FunctionDeclaration:
            case SyntaxKind.ClassDeclaration:
            {
                Debug.Assert(prefix.Length == 0 && suffix.Length == 0 && !privateName);
                var name = store.Name(node);
                if (!name.IsNone && !UtilitiesPublic.IsGeneratedIdentifier(store, name))
                {
                    return GenerateNameForNode(name, privateName: false, flags, prefix, suffix);
                }
                return GenerateNameForExportDefault();
            }
            case SyntaxKind.ExportAssignment:
                Debug.Assert(prefix.Length == 0 && suffix.Length == 0 && !privateName);
                return GenerateNameForExportDefault();
            case SyntaxKind.ClassExpression:
                Debug.Assert(prefix.Length == 0 && suffix.Length == 0 && !privateName);
                return GenerateNameForClassExpression();
            case SyntaxKind.MethodDeclaration:
            case SyntaxKind.GetAccessor:
            case SyntaxKind.SetAccessor:
                return GenerateNameForMethodOrAccessor(node, privateName, prefix, suffix);
            case SyntaxKind.ComputedPropertyName:
                return MakeTempVariableName(TempFlagsAuto, reservedInNestedScopes: true, privateName, prefix, suffix);
            default:
                return MakeTempVariableName(TempFlagsAuto, reservedInNestedScopes: false, privateName, prefix, suffix);
        }
    }

    /// <summary>Generates a unique identifier for a node.</summary>
    private string MakeName(Node name)
    {
        var autoGenerate = FactoryEmitNode.GetIdentifierAutoGenerate(store, name)!;
        var prefix = NodeFactory.FormatGeneratedNamePart(autoGenerate.Prefix);
        var suffix = NodeFactory.FormatGeneratedNamePart(autoGenerate.Suffix);
        var isPrivate = store.Kind(name) == SyntaxKind.PrivateIdentifier;
        switch (autoGenerate.Flags & GeneratedIdentifierFlags.KindMask)
        {
            case GeneratedIdentifierFlags.Auto:
                return MakeTempVariableName(TempFlagsAuto, (autoGenerate.Flags & GeneratedIdentifierFlags.ReservedInNestedScopes) != 0, isPrivate, prefix, suffix);
            case GeneratedIdentifierFlags.Loop:
                Debug.Assert(store.Kind(name) == SyntaxKind.Identifier);
                return MakeTempVariableName(TempFlags_i, (autoGenerate.Flags & GeneratedIdentifierFlags.ReservedInNestedScopes) != 0, privateName: false, prefix, suffix);
            case GeneratedIdentifierFlags.Unique:
                return MakeUniqueName(
                    PrinterUtilities.IdText(store, name),
                    (autoGenerate.Flags & GeneratedIdentifierFlags.FileLevel) != 0 ? IsFileLevelUniqueNameInCurrentFile : IsUniqueName,
                    (autoGenerate.Flags & GeneratedIdentifierFlags.Optimistic) != 0,
                    (autoGenerate.Flags & GeneratedIdentifierFlags.ReservedInNestedScopes) != 0,
                    isPrivate,
                    prefix,
                    suffix);
        }

        throw new InvalidOperationException("Unsupported GeneratedIdentifierKind: " + (autoGenerate.Flags & GeneratedIdentifierFlags.KindMask) + ".");
    }
