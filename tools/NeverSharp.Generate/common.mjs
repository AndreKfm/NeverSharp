import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const pins = JSON.parse(readFileSync(join(repoRoot, "pins.json"), "utf8"));
export const tsRoot = join(repoRoot, "external", "typescript");
export const outDir = join(repoRoot, "src", "Generated");

// The TypeScript compiler API of the pinned port source (typescript@6.0.3, integrity-checked by npm).
export const ts = createRequire(join(repoRoot, "harness", "astdump", "package.json"))("typescript");

export function header(source) {
    return [
        "// Copyright 2026 Andre Kaufmann",
        "// Portions Copyright (c) Microsoft Corporation.",
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        `// Generated from ${source}`,
        `//   https://github.com/microsoft/TypeScript at commit ${pins.references.typescript.commit}`,
        "// by tools/NeverSharp.Generate. Do not edit.",
        "// Modified: translated from TypeScript to C#.",
        "",
        "// <auto-generated />",
        "",
    ].join("\n");
}

export const csString = s => '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r/g, "\\r").replace(/\n/g, "\\n").replace(/\t/g, "\\t") + '"';
